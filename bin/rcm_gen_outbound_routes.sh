#!/bin/bash
set -euo pipefail

JSON_FILE="/etc/asterisk/rcm_outbound_routes.json"
OUT_CONF="/etc/asterisk/rcm_outbound_routes.conf"

need(){ command -v "$1" >/dev/null 2>&1 || { echo "ERROR: missing $1"; exit 1; }; }
need jq

ts(){ date +"%Y-%m-%d %H:%M:%S"; }

if [[ ! -f "$JSON_FILE" ]]; then
  echo "ERROR: $JSON_FILE not found"
  exit 1
fi

ROOT="$(jq -c '
  if type=="object" and (.routes|type=="array") then .
  elif type=="array" then {routes:.}
  else {routes:[]}
  end
' "$JSON_FILE")"

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

{
  echo "; ====================================================="
  echo "; RCM Outbound Routes - AUTOGENERATED"
  echo "; Generated: $(ts)"
  echo "; Source: $JSON_FILE"
  echo "; ====================================================="
  echo
} >"$TMP"

echo "$ROOT" | jq -c '.routes[]? | select(.enabled != false)' | while read -r r; do
  name="$(jq -r '.name // ""' <<<"$r")"
  ctx="$(jq -r '.context // ""' <<<"$r")"
  [[ -z "$ctx" ]] && continue

  timeout="$(jq -r '.timeout // 30' <<<"$r")"
  [[ "$timeout" =~ ^[0-9]+$ ]] || timeout=30

  time_limit_sec="$(jq -r '.time_limit_sec // 0' <<<"$r")"
  [[ "$time_limit_sec" =~ ^[0-9]+$ ]] || time_limit_sec=0
  LOPT=""
  if [[ "$time_limit_sec" -gt 0 ]]; then
    LOPT="L($((time_limit_sec*1000)))"
  fi

  strip="$(jq -r '.strip // 0' <<<"$r")"
  [[ "$strip" =~ ^[0-9]+$ ]] || strip=0

  prepend="$(jq -r '.prepend // ""' <<<"$r")"
  pin="$(jq -r '.pin // ""' <<<"$r")"
  record="$(jq -r '.record // false' <<<"$r")"
  [[ "$record" == "true" ]] && REC=1 || REC=0

  # trunks in order
  mapfile -t trunks < <(jq -r '.trunks[]? // empty' <<<"$r" | sed '/^$/d')
  [[ ${#trunks[@]} -eq 0 ]] && continue

  # patterns
  mapfile -t pats < <(jq -r '.patterns[]? // empty' <<<"$r" | sed '/^$/d')
  [[ ${#pats[@]} -eq 0 ]] && continue

  echo "[$ctx]" >>"$TMP"

  for pat in "${pats[@]}"; do
    # Dialplan core
    echo "exten => ${pat},1,NoOp(RCM-OUT route=${ctx} name=${name} caller=\${CALLERID(num)} ext=\${EXTEN})" >>"$TMP"

    # Use RCM_DIAL directly from EXTEN (no underscore = no inherited variable issues)
    echo " same => n,Set(RCM_DIAL=\${EXTEN})" >>"$TMP"

    # strip if needed
    if [[ "$strip" -gt 0 ]]; then
      echo " same => n,Set(RCM_DIAL=\${RCM_DIAL:${strip}})" >>"$TMP"
    fi

    # prepend if needed
    if [[ -n "$prepend" ]]; then
      echo " same => n,Set(RCM_DIAL=${prepend}\${RCM_DIAL})" >>"$TMP"
    fi

    # Authenticate (optional)
    if [[ -n "$pin" ]]; then
      echo " same => n,Authenticate(${pin})" >>"$TMP"
    fi

    # Recording (per route)
    if [[ "$REC" -eq 1 ]]; then
      echo " same => n,Set(CALLFILENAME=\${EXTEN}-\${CALLERID(num)}-\${STRFTIME(\${EPOCH},,%Y%m%d-%H%M%S)})" >>"$TMP"
      echo " same => n,MixMonitor(/var/spool/asterisk/monitor/\${CALLFILENAME}.wav,b)" >>"$TMP"
    fi

    # dial trunks sequential
    for t in "${trunks[@]}"; do
      if [[ -n "$LOPT" ]]; then
        echo " same => n,Dial(PJSIP/\${RCM_DIAL}@${t},${timeout},Tt${LOPT})" >>"$TMP"
      else
        echo " same => n,Dial(PJSIP/\${RCM_DIAL}@${t},${timeout},Tt)" >>"$TMP"
      fi
      echo " same => n,GotoIf(\$[\"\${DIALSTATUS}\"=\"ANSWER\"]?done)" >>"$TMP"
    done

    echo " same => n,Goto(done)" >>"$TMP"
    echo " same => n(done),Hangup()" >>"$TMP"
    echo >>"$TMP"
  done

  echo >>"$TMP"
done

install -m 0644 "$TMP" "$OUT_CONF"
echo "OK: generated $OUT_CONF"