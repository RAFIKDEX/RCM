#!/bin/bash
set -euo pipefail

GUI_ENDPOINTS="/etc/asterisk/pjsip.gui.endpoint.conf"
OUT="/etc/asterisk/context_exten.conf"

need_cmd() { command -v "$1" >/dev/null 2>&1 || { echo "ERROR: missing command: $1" >&2; exit 1; }; }
need_cmd awk
need_cmd sort
need_cmd uniq
need_cmd mktemp
need_cmd install

[[ -f "$GUI_ENDPOINTS" ]] || { echo "ERROR: $GUI_ENDPOINTS not found" >&2; exit 1; }

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

# Extract numeric section names like [2121]
mapfile -t exts < <(
  awk '
    /^\[[0-9]+\][[:space:]]*$/ {
      gsub(/^\[/,"",$0); gsub(/\]$/,"",$0);
      print $0
    }
  ' "$GUI_ENDPOINTS" | sort -n | uniq
)

umask 0022

{
  echo "; ========================================================="
  echo ";  AUTO-GENERATED FILE - DO NOT EDIT MANUALLY"
  echo ";  Generated by: /usr/local/bin/rcm_rebuild_context_exten.sh"
  echo ";  Source GUI  : $GUI_ENDPOINTS"
  echo ";  Date        : $(date -Is)"
  echo "; ========================================================="
  echo

  if [[ "${#exts[@]}" -eq 0 ]]; then
    echo "; WARNING: No extensions found in $GUI_ENDPOINTS"
    echo
  fi

  for e in "${exts[@]}"; do
    echo "[from-internal-${e}]"
    echo "include => internal"
    echo
    echo "; RCM-OUT-START"
    echo "; RCM-OUT-END"
    echo
  done
} > "$tmp"

install -m 0644 "$tmp" "$OUT"
echo "OK: rebuilt $OUT (extensions: ${#exts[@]})"
