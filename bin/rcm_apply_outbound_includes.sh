#!/bin/bash
set -euo pipefail

ROUTES_JSON="/etc/asterisk/rcm_outbound_routes.json"
RING_JSON="/etc/asterisk/rcm_ring_groups.json"
CTX_FILE="/etc/asterisk/context_exten.conf"
PJSIP_GUI_ENDPOINTS="/etc/asterisk/pjsip.gui.endpoint.conf"

START_MARK='; RCM-OUT-START'
END_MARKER='; RCM-OUT-END'

need() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "ERROR: missing command: $1" >&2
    exit 1
  }
}

need jq
need awk
need grep
need sed
need sort
need date
need cp
need mv
need mktemp

if [[ ! -f "$ROUTES_JSON" ]]; then
  echo "ERROR: $ROUTES_JSON not found" >&2
  exit 1
fi

if [[ ! -f "$PJSIP_GUI_ENDPOINTS" ]]; then
  echo "ERROR: $PJSIP_GUI_ENDPOINTS not found" >&2
  exit 1
fi

# -- Normalize JSON roots --------------------------------------

ROUTES_ROOT="$(
  jq -c '
    if type=="object" and (.routes|type=="array") then .
    elif type=="array" then {routes:.}
    else {routes:[]}
    end
  ' "$ROUTES_JSON"
)"

RING_ROOT='{"groups":[]}'
if [[ -f "$RING_JSON" ]]; then
  RING_ROOT="$(
    jq -c '
      if type=="object" and (.groups|type=="array") then .
      elif type=="array" then {groups:.}
      else {groups:[]}
      end
    ' "$RING_JSON"
  )"
fi

# -- rebuild_context_exten -------------------------------------
rebuild_context_exten() {
  local tmp
  tmp="$(mktemp)"

  {
    echo "; AUTOGENERATED by rcm_apply_outbound_includes.sh"
    echo "; Generated: $(date -Is)"
    echo

    grep -E '^\[[0-9]+\]$' "$PJSIP_GUI_ENDPOINTS" \
      | tr -d '[]' \
      | sort -V \
      | while IFS= read -r ext; do
          [[ -n "$ext" ]] || continue
          echo "[from-internal-$ext]"
          echo "include => internal"
          echo
          echo "$START_MARK"
          echo "$END_MARKER"
          echo
        done
  } > "$tmp"

  install -m 0644 "$tmp" "$CTX_FILE"
  rm -f "$tmp"
  echo "OK: rebuilt $CTX_FILE"
}

# Rebuild if missing or empty
if [[ ! -f "$CTX_FILE" || ! -s "$CTX_FILE" ]]; then
  rebuild_context_exten
fi

# -- group_members helper --------------------------------------
group_members() {
  local gid="$1"
  echo "$RING_ROOT" | jq -r --arg gid "$gid" '
    (.groups // [])
    | map(select((.id|tostring)==$gid and (.enabled != false)))
    | .[0].members[]? // empty
  ' 2>/dev/null || true
}

# -- Build EXT|ROUTE_CONTEXT mapping --------------------------

TMP_WANT="$(mktemp)"
TMP_SORTED="$(mktemp)"
TMP_OUT="$(mktemp)"

cleanup() {
  rm -f "$TMP_WANT" "$TMP_SORTED" "$TMP_OUT"
}
trap cleanup EXIT

: > "$TMP_WANT"

while IFS= read -r route; do
  [[ -n "$route" ]] || continue

  route_ctx="$(jq -r '.context // ""' <<<"$route")"
  enabled="$(jq -r '.enabled // true' <<<"$route")"
  mode="$(jq -r '.mode // "whitelist"' <<<"$route")"

  [[ "$enabled" == "true" ]] || continue
  [[ -n "$route_ctx" ]] || continue

  if [[ "$mode" == "groups" ]]; then
    while IFS= read -r gid; do
      [[ -n "$gid" ]] || continue
      while IFS= read -r member; do
        [[ -n "$member" ]] || continue
        member="$(echo "$member" | sed 's/[^0-9]//g')"
        [[ -n "$member" ]] || continue
        echo "${member}|${route_ctx}" >> "$TMP_WANT"
      done < <(group_members "$gid")
    done < <(jq -r '.groups[]? // empty' <<<"$route")
  else
    while IFS= read -r ext; do
      [[ -n "$ext" ]] || continue
      ext="$(echo "$ext" | sed 's/[^0-9]//g')"
      [[ -n "$ext" ]] || continue
      echo "${ext}|${route_ctx}" >> "$TMP_WANT"
    done < <(jq -r '.whitelist[]? // empty' <<<"$route")
  fi
done < <(echo "$ROUTES_ROOT" | jq -c '.routes[]?')

sort -u "$TMP_WANT" > "$TMP_SORTED"

# -- Apply includes inside marker blocks -----------------------
awk \
  -v START_LINE="$START_MARK" \
  -v END_LINE="$END_MARKER" \
  -v WANTFILE="$TMP_SORTED" \
'
BEGIN {
  while ((getline line < WANTFILE) > 0) {
    split(line, a, "|")
    ext  = a[1]
    rctx = a[2]
    if (ext != "" && rctx != "") {
      wanted[ext] = wanted[ext] rctx "\n"
    }
  }
  close(WANTFILE)
  in_marker_block = 0
  current_ext = ""
}

/^\[from-internal-[0-9]+\]$/ {
  current_ext = $0
  gsub(/^\[from-internal-/, "", current_ext)
  gsub(/\]$/, "", current_ext)
  print
  next
}

$0 == START_LINE {
  print
  in_marker_block = 1

  if (current_ext in wanted) {
    count = split(wanted[current_ext], arr, "\n")
    delete printed
    for (i = 1; i <= count; i++) {
      if (arr[i] != "" && !(arr[i] in printed)) {
        print "include => " arr[i]
        printed[arr[i]] = 1
      }
    }
  }
  next
}

$0 == END_LINE {
  in_marker_block = 0
  print
  next
}

in_marker_block == 1 {
  next
}

{
  print
}
' "$CTX_FILE" > "$TMP_OUT"

cp -a "$CTX_FILE" "$CTX_FILE.bak.$(date +%F_%H%M%S)" 2>/dev/null || true
mv "$TMP_OUT" "$CTX_FILE"

echo "OK: applied includes into markers in $CTX_FILE"